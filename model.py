# Step 1 - build_token_to_id_vocab
def build_token_to_id_vocab(sentences, specials=('<pad>', '<bos>', '<eos>', '<unk>')):
    # TODO: build a token-to-id dict with specials first, then corpus tokens in first-seen order.
    token_to_id = {specials[i]: i for i in range(len(specials))}
    vocab_count = len(token_to_id)
    for sentence in sentences:
        words = sentence.split(" ")
        for word in words:
            if word not in token_to_id:
                token_to_id[word] = vocab_count
                vocab_count += 1

    return token_to_id

# Step 2 - build_id_to_token_vocab
def build_id_to_token_vocab(token_to_id):
    # TODO: build the inverse id-to-token dictionary from token_to_id
    id_to_token = {value: key for key, value in token_to_id.items()}
    return id_to_token

# Step 3 - encode_sentence_to_ids
def encode_sentence_to_ids(sentence, token_to_id, unk_token='<unk>'):
    # TODO: convert whitespace tokens of `sentence` to ids via `token_to_id`, using `unk_token`'s id for OOV
    if len(sentence) == 0:
        return []
    tokens = sentence.split(" ")
    sentence_token_ids = []
    for token in tokens:
        token_id = token_to_id.get(token, token_to_id[unk_token])
        sentence_token_ids.append(token_id)

    return sentence_token_ids

# Step 4 - decode_ids_to_tokens
def decode_ids_to_tokens(ids, id_to_token):
    # TODO: map each id in ids to its token string via id_to_token and return the list
    tokens = []
    for token_id in ids:
        tokens.append(id_to_token[token_id])
    
    return tokens

# Step 5 - pad_id_sequence
def pad_id_sequence(ids, max_len, pad_id):
    # TODO: return a list of length exactly max_len, padding with pad_id or truncating.
    n = len(ids)
    if n < max_len:
        ids = ids + [pad_id] * (max_len - n)
    elif n > max_len:
        ids = ids[:max_len]
    
    return ids

